#!/usr/bin/env node
/**
 * Phase 9 lab — schema Patch envelope + product import gates.
 * Requires SPECULUM_MONOREPO_ROOT (or --monorepo-root=). Never infers via ../.
 */
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

function usage() {
  console.error(
    'FAIL lab-schema-ingest: monorepo root required.\n' +
      '  Set SPECULUM_MONOREPO_ROOT to the Speculum checkout that contains packages/page-projection,\n' +
      '  or pass --monorepo-root=/path/to/Websete Speculum\n' +
      '  WSL trees that only mount gecko-engine do not include packages/ — that is a workspace design\n' +
      '  issue; run this gate on the full checkout (or mount packages) after exporting the root.',
  );
}

let monorepo = process.env.SPECULUM_MONOREPO_ROOT || '';
for (const a of process.argv.slice(2)) {
  if (a.startsWith('--monorepo-root=')) monorepo = a.slice('--monorepo-root='.length);
}

if (!monorepo) {
  usage();
  process.exit(1);
}
if (!existsSync(monorepo)) {
  console.error(`FAIL lab-schema-ingest: SPECULUM_MONOREPO_ROOT does not exist: ${monorepo}`);
  process.exit(1);
}

const pp = join(monorepo, 'packages/page-projection/src');
const genPath = join(pp, 'wire/speculum_wire.gen.ts');
if (!existsSync(genPath)) {
  console.error(
    `FAIL lab-schema-ingest: missing ${genPath}\n` +
      `  monorepo root was ${monorepo} — packages/page-projection not present there.`,
  );
  process.exit(1);
}

const schemaPath = join(pp, 'wire/schemaPatch.ts');
const clientPath = join(pp, 'projected/ProjectionClient.ts');

let fails = 0;
function check(c, m) {
  if (!c) {
    console.error('FAIL', m);
    fails++;
  }
}

const gen = readFileSync(genPath, 'utf8');
check(gen.includes('GENERATED by wiregen'), 'gen header');
check(gen.includes('export const OPC_Patch = 0x8401'), 'OPC_Patch');
check(gen.includes('export function decodePatchBytes'), 'decodePatchBytes');

const schema = readFileSync(schemaPath, 'utf8');
check(schema.includes("from './speculum_wire.gen'"), 'schemaPatch imports gen');
check(schema.includes('export function decodeSchemaPatchMessage'), 'decodeSchemaPatchMessage');
check(schema.includes('export function encodeSchemaPatchMessage'), 'encodeSchemaPatchMessage');

const client = readFileSync(clientPath, 'utf8');
check(client.includes("from '../wire/schemaPatch'"), 'ProjectionClient imports schemaPatch');
check(client.includes('decodeSchemaPatchMessage'), 'uses decodeSchemaPatchMessage');
check(client.includes('isSchemaWire'), 'uses isSchemaWire');
check(client.includes('checkPtrEqualsPn') || client.includes('verifyDescriptors'), 'descriptor hop');
check(client.includes('assertDescriptors'), 'assertDescriptors option');

const desc = readFileSync(join(pp, 'core/descriptorEquality.ts'), 'utf8');
check(desc.includes('export function checkPtrEqualsPn'), 'checkPtrEqualsPn');

if (fails) {
  console.error(`lab-schema-ingest FAIL (${fails})`);
  process.exit(1);
}
console.log('lab-schema-ingest PASS — gen codec hop live in ProjectionClient');
console.log('Real page: ProjectionClient.create({ assertDescriptors: true }) + Session Mirror');
